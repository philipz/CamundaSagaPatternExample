#!/usr/bin/env python3
"""Transcribe Quint ITF counterexample traces into Lean (`Specs/Traces.lean`).

Usage:  python3 gen_traces.py [../quint/traces] > Specs/Traces.lean

Every file `<instance>__<BRk>.itf.json` becomes
  * `def tr_<instance>_<BRk> : QTrace`  (config, initial choices, projected states, events)
  * `theorem quint_<instance>_<BRk> : TraceConfirmed tr_<instance>_<BRk> BRk`
The theorem proofs are filled in only after owner sign-off (phase 4); until then `PROOF` below
is `sorry`. Pass `--prove` to emit the real proof term.
"""
import glob
import json
import os
import sys

CFG = {  # (redelivery, bookFailure, cancelFailure, flightRefBug) — bookHolidayInstances.qnt
    "ideal": "idealCfg", "asIs": "asIsCfg", "redelivery": "redeliveryCfg",
    "bookFailure": "bookFailureCfg", "cancelFailure": "cancelFailureCfg",
    "allFaults": "allFaultsCfg",
}
ITEMS = ["Flight", "Train", "Hotel"]
LITEM = {"Flight": ".flight", "Train": ".train", "Hotel": ".hotel"}
LSTATUS = {"NoBooking": ".noBooking", "Confirmed": ".confirmed", "Canceled": ".canceled"}
LPHASE = {"Booking": ".booking", "Review": ".review", "Compensating": ".compensating",
          "Ended": ".ended"}
LEVENT = {"Fetched": "fetch", "SideEffect": "sideEffect", "HandlerFailed": "handlerFail",
          "LockExpired": "lockExpire", "Completed": "complete"}


def val(v):
    if isinstance(v, dict):
        if "#bigint" in v:
            return int(v["#bigint"])
        if "#set" in v:
            return sorted(val(x) for x in v["#set"])
        if "#map" in v:
            return [(val(k), val(x)) for k, x in v["#map"]]
        if "#tup" in v:
            return tuple(val(x) for x in v["#tup"])
        if "tag" in v:
            return (v["tag"], val(v["value"]))
        return {k: val(x) for k, x in v.items()}
    return v


def tag(x):
    return x[0]


def mp(pairs):
    """map with sum-type keys → dict keyed by tag string (or (tag, inner-tag))."""
    out = {}
    for k, v in pairs:
        if isinstance(k, tuple) and isinstance(k[1], tuple) and k[1] != ():
            out[(k[0], k[1][0])] = v
        else:
            out[k[0]] = v
    return out


def b(x):
    return "true" if x else "false"


def lean_list(xs):
    return "[" + ", ".join(str(x) for x in xs) + "]"


def lean_task(t):
    if tag(t) == "Absent":
        return ".absent"
    if tag(t) == "Available":
        return ".available"
    info = t[1]
    return f"(.locked {b(info['sideEffectDone'])} {info['targetRef']} {info['returnRef']})"


def lean_kind_item(k):
    return f".{'book' if k[0] == 'Book' else 'cancel'} {LITEM[k[1][0]]}"


def lean_event(ev):
    t = tag(ev)
    if t == "UserConfirmed":
        return ".userConfirm"
    if t == "UserCanceled":
        return ".userCancel"
    return f"(.{LEVENT[t]} {lean_kind_item(ev[1])})"


def project(st):
    s = {k.split("::")[-1]: val(v) for k, v in st.items() if k != "#meta"}
    e, sup = s["engine"], s["supplier"]
    tasks = mp(s["tasks"])
    need, bd, status, ref = mp(e["need"]), mp(e["branchDone"]), mp(e["status"]), mp(e["ref"])
    active, ever = mp(sup["active"]), mp(sup["everBooked"])
    down, cdown = mp(sup["down"]), mp(sup["cancelDown"])
    subs = {x[0] for x in e["compSubs"]}
    items = []
    for i in ITEMS:
        items.append(
            "{ need := %s, branchDone := %s, status := %s, ref := %d, sub := %s, "
            "book := %s, cancel := %s, active := %s, ever := %s, down := %s, cancelDown := %s }"
            % (b(need[i]), b(bd[i]), LSTATUS[tag(status[i])], ref[i], b(i in subs),
               lean_task(tasks[("Book", i)]), lean_task(tasks[("Cancel", i)]),
               lean_list(active[i]), lean_list(ever[i]), b(down[i]), b(cdown[i])))
    state = ("{ phase := %s, userCanceled := %s, nextRef := %d,\n      items := fun\n"
             "        | .flight => %s\n        | .train => %s\n        | .hotel => %s }"
             % (LPHASE[tag(e["phase"])], b(e["userCanceled"]), sup["nextRef"], *items))
    triples = tuple(f"(ofTriple {b(m[ITEMS[0]])} {b(m[ITEMS[1]])} {b(m[ITEMS[2]])})"
                    for m in (need, down, cdown))
    return state, s["lastEvent"], triples


def main():
    args = [a for a in sys.argv[1:] if not a.startswith("--")]
    prove = "--prove" in sys.argv
    src = args[0] if args else os.path.join(os.path.dirname(__file__), "..", "quint", "traces")
    files = sorted(glob.glob(os.path.join(src, "*.itf.json")))
    print("import Specs.Proofs\n/-\nAUTO-GENERATED by gen_traces.py from specs/quint/traces/*.itf.json"
          " — do not edit.\nOne QTrace + one TraceConfirmed theorem per Quint counterexample.\n-/\n")
    print("namespace Saga\n")
    print("set_option maxRecDepth 100000\n")
    names = []
    for f in files:
        base = os.path.basename(f)[: -len(".itf.json")]
        inst, rule = base.split("__")
        d = json.load(open(f))
        prefixes = {k.split("::")[0] for k in d["vars"]}
        assert prefixes == {inst}, f"{base}: ITF module prefix {prefixes} != filename instance {inst}"
        projected = [project(st) for st in d["states"]]
        name = f"{inst}_{rule}"
        names.append((name, rule))
        need, down, cdown = projected[0][2]
        print(f"/-- Quint `{inst}` / {rule}: {len(projected) - 1} steps (`traces/{base}.md`). -/")
        print(f"def tr_{name} : QTrace where")
        print(f"  cfg := {CFG[inst]}")
        print(f"  need := {need}\n  down := {down}\n  cdown := {cdown}")
        print("  states := [\n    " + ",\n    ".join(p[0] for p in projected) + "]")
        print("  events := [" + ", ".join(lean_event(p[1]) for p in projected[1:]) + "]\n")
        proof = "traceConfirmed_of_check _ _ (by decide) (by decide)" if prove else "sorry"
        print(f"theorem quint_{name} : TraceConfirmed tr_{name} {rule} :=\n  {proof}\n")
    print("end Saga")
    sys.stderr.write(f"generated {len(names)} traces\n")


if __name__ == "__main__":
    main()
